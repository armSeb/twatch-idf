def preview(path, scale=6):
    from PIL import Image, ImageDraw
    check()
    col = {ch: ((c >> 16) & 255, (c >> 8) & 255, c & 255, 255) for ch, _, c in PAL if c is not None}

    def img(g, eyes=None, mouth=None, e='OPEN', mo='SMILE'):
        g = [list(r) for r in g]
        def put(spr, x, y):
            for j, r in enumerate(spr):
                for i, ch in enumerate(r):
                    if ch != '.' and 0 <= y + j < len(g) and 0 <= x + i < len(g[0]):
                        g[y + j][x + i] = ch
        if eyes:
            for (x, y) in eyes: put(EYES[e], x, y)
        if mouth: put(MOUTHS[mo], *mouth)
        im = Image.new('RGBA', (len(g[0]) * scale, len(g) * scale), (0, 0, 0, 0))
        d = ImageDraw.Draw(im)
        for y, r in enumerate(g):
            for x, ch in enumerate(r):
                if ch != '.':
                    d.rectangle([x * scale, y * scale, x * scale + scale - 1, y * scale + scale - 1], fill=col[ch])
        return im
    tiles = []
    for k, b in BODIES.items():
        for i, f in enumerate(b['frames']):
            tiles.append(img(grid(f), b['eyes'], b['mouth'], 'OPEN', 'SMILE'))
        for e, mo in (('HAPPY', 'OPEN'), ('CLOSED', 'NONE'), ('SAD', 'FROWN'), ('SICK', 'FLAT')):
            tiles.append(img(grid(b['frames'][0]), b['eyes'], b['mouth'], e, mo))
    for s in EGG: tiles.append(img(grid(s)))
    for k, s in ITEMS.items(): tiles.append(img(grid(s)))
    W = 1200
    x = y = 10; rowh = 0; pos = []
    for t in tiles:
        if x + t.width > W - 10: x = 10; y += rowh + 10; rowh = 0
        pos.append((x, y)); x += t.width + 10; rowh = max(rowh, t.height)
    sheet = Image.new('RGB', (W, y + rowh + 10), (90, 160, 90))
    for t, p in zip(tiles, pos): sheet.paste(t, p, t)
    sheet.save(path)


